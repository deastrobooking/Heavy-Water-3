pub const page_count = pages.len;
/// Longest line the panel shows without clipping (canvas characters at the guide's text size).
pub const max_line = 82;

test "every guide line fits the panel and every page fits its height" {
    for (pages) |page| {
        try std.testing.expect(page.lines.len <= 11);
        for (page.lines) |line| try std.testing.expect(line.len <= max_line);
    }
}
